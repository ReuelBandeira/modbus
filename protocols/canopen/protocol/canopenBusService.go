func ParseCanBusFrame(inCanFrame *can.Frame) error {
	// Check if inCanFrame is not null and is CanOpen
	if inCanFrame == nil {
		return fmt.Errorf("FAIL: incanframe= null")
	}
	rawCanBusFrame, err := ConvertCanBusFrameToBytes(inCanFrame)
	if err != nil {
		logPkg.CtsLog.Error("Error: err[%s]", err)
		return err
	}
	isCanOpen, err := ParseRawCanBusFrame(rawCanBusFrame)
	if err != nil {
		logPkg.CtsLog.Error("Error:isCanOpen[%v]  err[%s]", isCanOpen, err)
		return err
	}
	return nil
}

// This Function decodes detailed of CANopen byte array message
// if all required data are present return nil else return error message explaining the reason of failure
func ParseRawCanBusFrame(rawCanBusFrame []byte) (bool, error) {
	// Converte Raw CAN Frame to CAN frame
	if rawCanBusFrame == nil {
		logPkg.CtsLog.Error("ParseRawCanBusFrame:ER can frame=nil CANRawFrame[%X]", len(rawCanBusFrame))
		return false, fmt.Errorf("ParseRawCanBusFrame:ER can frame=nil CANRawFrame[%X]", len(rawCanBusFrame))
	} else if len(rawCanBusFrame) < 4 {
		logPkg.CtsLog.Error("ParseRawCanBusFrame:ER can frame Too Short Exp len(CANRawFrame) >=4 rcv len(CANRawFrame)[%d]", len(rawCanBusFrame))
		return false, fmt.Errorf("ParseRawCanBusFrame:ER can frame Too Short Exp len(CANRawFrame) >=4 rcv len(CANRawFrame)[%d]", len(rawCanBusFrame))
	} else if len(rawCanBusFrame) > 13 {
		logPkg.CtsLog.Error("ParseRawCanBusFrame:ER can frame Too long Exp len(data) <=13 rcv len(data)[%d]", len(rawCanBusFrame))
		return false, fmt.Errorf("ParseRawCanBusFrame:ER can frame too long Exp len(data) <=13 rcv len(data)[%d]", len(rawCanBusFrame))
	}

	id := binary.BigEndian.Uint32(rawCanBusFrame[:4]) // Bytes 0-3
	dlc := rawCanBusFrame[4] & 0x0F                   // Byte 4 b0-3
	ext := (rawCanBusFrame[4] & 0x80) != 0            // Byte 4 b7
	rtr := (rawCanBusFrame[4] & 0x40) != 0            // Byte 4 b6
	if len(rawCanBusFrame) < int(dlc)+5 {
		logPkg.CtsLog.Error("ParseRawCanBusFrame:ER invalid can frame len(CANRawFrame)[%d] < int(dlc)+4[%d]", len(rawCanBusFrame), int(dlc)+5)
		return false, fmt.Errorf("ParseRawCanBusFrame:ER invalid can frame len(CANRawFrame)[%d] < int(dlc)+4[%d]", len(rawCanBusFrame), int(dlc)+5)
	} else if len(rawCanBusFrame) > int(dlc)+5 {
		logPkg.CtsLog.Error("ParseRawCanBusFrame:ER invalid can frame len(data)[%d] > int(dlc)+4[%d]", len(rawCanBusFrame), int(dlc)+5)
		return false, fmt.Errorf("ParseRawCanBusFrame:ER invalid can frame len(data)[%d] > int(dlc)+4[%d]", len(rawCanBusFrame), int(dlc)+5)
	}
	// It is a CanBus frame, now we check if it is a CANopen frame present on CanBus
	canFrame := &CANOPEN_Frame{ // canopenControl.go
		ID:   id,                        // 32 bits bytes 0-3
		DLC:  dlc,                       //  4 Bits byte  4 bits (0-3) byte 4 b7 ext byte 4 b6 RNR byte 4 bits 4-5 N/A
		Data: rawCanBusFrame[5 : 5+dlc], //  8 Bits Bytes 5-12
	}
	if canFrame.DLC != uint8(len(canFrame.Data)) {
		logPkg.CtsLog.Error("ParseRawCanBusFrame:ER invalid can frame: canFrame DLC[%d] != len(canFrame Data)[%d]", canFrame.DLC, len(canFrame.Data))
		return false, fmt.Errorf("ParseRawCanBusFrame:ER invalid can frame: canFrame DLC[%d] != len(canFrame Data)[%d]", canFrame.DLC, len(canFrame.Data))
	}
	if !ext {
		// CIA301a: ID = 11 bits
		err := ParseCANopen_CIA301aFrame(canFrame) // canopenControl.go
		if err != nil {
			///FAIL to Parse a CANopen Frame
			logPkg.CtsLog.Warn("ParseRawCanBusFrame:WR Is a CAN frame but not CANopen Frame msg[%s]", err)
			return false, nil
		}
	} else {
		// CIA301b: ID = 29 bits
		err := ParseCANopen_CIA301bFrame(canFrame) // canopenControl.go
		if err != nil {
			logPkg.CtsLog.Warn("ParseRawCanBusFrame:WR Is a CAN frame but not CANopen Frame msg[%s]", err)
			return false, nil
		}
	}
	// Valid CANopen Frame was Read on CanBus interface
	logPkg.CtsLog.Debug("ParseRawCanBusFrame:OK << ParseRawCanBusFrame[%X] id[%X] dlc[%d] ext[%v] rtr[%v] data[%X]Valid CANopen Frame was Read on CanBus interface", rawCanBusFrame, id, dlc, ext, rtr, canFrame.Data)
	return true, nil
}

func ConvertCanBusFrameToBytes(inCanFrame *can.Frame) ([]byte, error) {
	// Determine the length of the CAN frame
	frameLength := len(inCanFrame.Data) + 5 // CanFame id(4) DLC(1)

	// CANopenTcpServer_Create a byte slice with the appropriate length
	outRawCanFrame := make([]byte, frameLength)
	outRawCanFrame[0] = byte(inCanFrame.ArbitrationID >> 24)
	outRawCanFrame[1] = byte(inCanFrame.ArbitrationID >> 16)
	outRawCanFrame[2] = byte(inCanFrame.ArbitrationID >> 8)
	outRawCanFrame[3] = byte(inCanFrame.ArbitrationID)
	outRawCanFrame[4] = byte(inCanFrame.DLC)
	for i := 0; i < len(inCanFrame.Data); i++ {
		outRawCanFrame[i+5] = inCanFrame.Data[i]
	}
	return outRawCanFrame, nil
}

func ConvertRawBytesToCanBusFrame(inRawCanFrame []byte) (*can.Frame, error) {
	if inRawCanFrame == nil {
		logPkg.CtsLog.Error("ConvertRawBytesToCanBusFrame:ER can frame=nil CANRawFrame[%X]", len(inRawCanFrame))
		return nil, fmt.Errorf("ConvertRawBytesToCanBusFrame:ER can frame=nil CANRawFrame[%X]", len(inRawCanFrame))
	} else if len(inRawCanFrame) < 4 {
		logPkg.CtsLog.Error("ConvertRawBytesToCanBusFrame:ER can frame Too Short Exp len(CANRawFrame) >=4 rcv len(CANRawFrame)[%d]", len(inRawCanFrame))
		return nil, fmt.Errorf("ConvertRawBytesToCanBusFrame:ER can frame Too Short Exp len(CANRawFrame) >=4 rcv len(CANRawFrame)[%d]", len(inRawCanFrame))
	} else if len(inRawCanFrame) > 13 {
		logPkg.CtsLog.Error("ConvertRawBytesToCanBusFrame:ER can frame Too long Exp len(data) <=13 rcv len(data)[%d]", len(inRawCanFrame))
		return nil, fmt.Errorf("ConvertRawBytesToCanBusFrame:ER can frame too long Exp len(data) <=13 rcv len(data)[%d]", len(inRawCanFrame))
	}
	//CanFrame ID = 32 bits
	id := uint32(inRawCanFrame[0]) << 24
	id += uint32(inRawCanFrame[1]) << 16
	id += uint32(inRawCanFrame[2]) << 8
	id += uint32(inRawCanFrame[3])
	//CanFrame DLC = 4 byts
	dlc := inRawCanFrame[4] & 0x0F
	if int(dlc) != len(inRawCanFrame)-4 {
		logPkg.CtsLog.Error("ConvertRawBytesToCanBusFrame:ER can frame Too long Exp len(data) <=13 rcv len(data)[%d]", len(inRawCanFrame))
		return nil, fmt.Errorf("ConvertRawBytesToCanBusFrame:ER can frame too long Exp len(data) <=13 rcv len(data)[%d]", len(inRawCanFrame))
	}
	i := 0
	// Looks line a CanBus frame
	//CanFrame Data = 0-8 bytes
	var data [8]byte
	for {
		if i > int(dlc) {
			break
		}
		data[i] = inRawCanFrame[i+4]
	}
	canBusFrame := &can.Frame{
		ArbitrationID: id,  //  ID + RTR
		DLC:           dlc, // Data Length
		Data:          data,
	}
	return canBusFrame, nil
}
